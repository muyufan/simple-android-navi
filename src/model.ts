import * as fs from 'node:fs';
import * as path from 'node:path';
import type { Model, ModelEntry } from './types';

const MARKER = 'generated by android-navi';

export interface PlannedFile {
  filePath: string;
  contents: string;
}

export interface Plan {
  files: PlannedFile[];
  projectNames: Map<string, string>;
  /** Module dirs that already contain a `.project` we did not create. */
  conflicts: string[];
  missingLibs: string[];
}

export function projectNameFor(gradlePath: string): string {
  const trimmed = gradlePath.replace(/^:/, '').replace(/:/g, '-');
  return `ani-${trimmed}`;
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function toPosix(value: string): string {
  return value.replace(/\\/g, '/');
}

function projectDescription(name: string, referenced: string[]): string {
  const projects = referenced.map((r) => `    <project>${escapeXml(r)}</project>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<projectDescription>
  <name>${escapeXml(name)}</name>
  <comment>${MARKER}. Regenerated on every sync; do not edit.</comment>
  <projects>
${projects}
  </projects>
  <buildSpec>
    <buildCommand>
      <name>org.eclipse.jdt.core.javabuilder</name>
      <arguments></arguments>
    </buildCommand>
  </buildSpec>
  <natures>
    <nature>org.eclipse.jdt.core.javanature</nature>
  </natures>
</projectDescription>
`;
}

function classpath(entry: ModelEntry, names: Map<string, string>): string {
  const lines: string[] = [];

  for (const dir of entry.sourceDirs ?? []) {
    if (!fs.existsSync(dir)) continue; // e.g. src/debug/java that does not exist in this repo
    lines.push(`  <classpathentry kind="src" path="${escapeXml(toPosix(path.relative(entry.moduleDir, dir)))}"/>`);
  }

  lines.push('  <classpathentry kind="con" path="org.eclipse.jdt.launching.JRE_CONTAINER"/>');

  for (const ref of entry.projectRefs ?? []) {
    const target = names.get(ref.project);
    if (!target) continue;
    lines.push(`  <classpathentry combineaccessrules="false" kind="src" path="/${escapeXml(target)}"/>`);
  }

  // android.jar (bootClasspath) must be a plain lib next to the JRE container: verified to resolve
  // android.* without duplicate platform class errors.
  const libs = [...(entry.libs ?? []), ...(entry.bootClasspath ?? [])];
  for (const lib of libs) {
    if (!fs.existsSync(lib)) continue;
    // Always absolute: the model is machine-local (Gradle cache paths), and the verified-good
    // model used absolute paths for every jar, including the module's own R.jar.
    const portable = lib;
    lines.push(`  <classpathentry kind="lib" exported="true" path="${escapeXml(portable)}"/>`);
  }

  lines.push(`  <classpathentry kind="output" path="bin/${escapeXml(entry.variant)}"/>`);

  return `<?xml version="1.0" encoding="UTF-8"?>
<classpath>
${lines.join('\n')}
</classpath>
`;
}

/** Builds the file contents for a whole workspace: one Eclipse project per Gradle module. */
export function planModel(model: Model, variant: string): Plan {
  const entries = model.entries.filter((e) => e.variant === variant);
  const names = new Map<string, string>();
  for (const entry of entries) names.set(entry.project, projectNameFor(entry.project));

  const files: PlannedFile[] = [];
  const conflicts: string[] = [];
  const missingLibs: string[] = [];

  for (const entry of entries) {
    const projectFile = path.join(entry.moduleDir, '.project');
    if (fs.existsSync(projectFile) && !fs.readFileSync(projectFile, 'utf8').includes(MARKER)) {
      conflicts.push(projectFile);
      continue;
    }
    for (const lib of [...(entry.libs ?? []), ...(entry.bootClasspath ?? [])]) {
      if (!fs.existsSync(lib)) missingLibs.push(lib);
    }
    const name = names.get(entry.project)!;
    const referenced = (entry.projectRefs ?? [])
      .map((r) => names.get(r.project))
      .filter((v): v is string => Boolean(v));
    files.push({ filePath: projectFile, contents: projectDescription(name, referenced) });
    files.push({
      filePath: path.join(entry.moduleDir, '.classpath'),
      contents: classpath(entry, names),
    });
  }

  return { files, projectNames: names, conflicts, missingLibs };
}

export function writePlan(plan: Plan): string[] {
  const written: string[] = [];
  for (const file of plan.files) {
    const tmp = `${file.filePath}.tmp`;
    fs.writeFileSync(tmp, file.contents, 'utf8');
    fs.renameSync(tmp, file.filePath);
    written.push(file.filePath);
  }
  return written;
}

/** Keeps the generated model out of `git status` without touching a tracked file. */
export function excludeFromGit(projectRoot: string, filePaths: string[]): void {
  const gitDir = path.join(projectRoot, '.git');
  if (!fs.existsSync(gitDir)) return;
  const excludeFile = path.join(gitDir, 'info', 'exclude');
  fs.mkdirSync(path.dirname(excludeFile), { recursive: true });
  const existing = fs.existsSync(excludeFile) ? fs.readFileSync(excludeFile, 'utf8') : '';
  const lines = new Set(existing.split(/\r?\n/).filter(Boolean));
  let changed = false;
  for (const filePath of filePaths) {
    const entry = `/${toPosix(path.relative(projectRoot, filePath))}`;
    if (!lines.has(entry)) {
      lines.add(entry);
      changed = true;
    }
  }
  if (!changed) return;
  fs.writeFileSync(excludeFile, `${[...lines].join('\n')}\n`, 'utf8');
}
